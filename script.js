const botonIdioma =
    document.getElementById("boton-idioma");

const ventanaIdiomas =
    document.getElementById("ventana-idiomas");


botonIdioma.addEventListener("click", () => {

    ventanaIdiomas.classList.toggle("mostrar");

});


// ============================================
// 🌎 CAMBIAR IDIOMA
// ============================================

document.querySelectorAll(".idioma").forEach(boton => {

    boton.addEventListener("click", () => {

        cambiarIdioma(boton.dataset.idioma);

        ventanaIdiomas.classList.remove("mostrar");

    });

});


function cambiarIdioma(idioma) {

    const t = traducciones[idioma];

    if (!t) return;


    // ========================================
    // TÍTULO
    // ========================================

    const titulo = document.querySelector("h1");

    if (titulo) {

        titulo.innerHTML =
            `<span class="inicial">${t.titulo.charAt(0)}</span>${t.titulo.slice(1)}`;

    }


    // ========================================
    // PÁRRAFO PRINCIPAL
    // ========================================

    const parrafos = document.querySelectorAll("body > p");

    if (parrafos[0]) {

        parrafos[0].textContent =
            t.descripcion;

    }


    // ========================================
    // TÍTULOS
    // ========================================

    const h2 = document.querySelectorAll("body > h2");

    if (h2[0]) {

        h2[0].textContent =
            t.unirte;

    }

    if (h2[1]) {

        h2[1].textContent =
            t.reglas;

    }


    // ========================================
    // TEXTOS DEL GRUPO
    // ========================================

    const textos = document.querySelectorAll("body > p");

    if (textos[1]) textos[1].textContent = t.aburrido;
    if (textos[2]) textos[2].textContent = t.grupito;
    if (textos[3]) textos[3].textContent = t.descripcionGrupo;
    if (textos[4]) textos[4].textContent = t.desastre;


    // ========================================
    // REGLAS
    // ========================================

    const reglas =
        document.querySelectorAll(".reglas p");


    if (reglas[0])
        reglas[0].textContent = t.presentate;

    if (reglas[1])
        reglas[1].textContent = t.edad;

    if (reglas[2])
        reglas[2].textContent = t.respeto;

    if (reglas[3])
        reglas[3].textContent = t.spam;

    if (reglas[4])
        reglas[4].textContent = t.gore;

    if (reglas[5])
        reglas[5].textContent = t.dm;

    if (reglas[6])
        reglas[6].textContent = t.disfruta;

    if (reglas[7])
        reglas[7].textContent = t.asistencia;

    if (reglas[8])
        reglas[8].textContent = t.expulsión;


    // ========================================
    // BOTÓN
    // ========================================

    const botonUnirse =
        document.querySelector("a button");

    if (botonUnirse) {

        botonUnirse.textContent =
            t.boton;

    }


    // ========================================
    // INDICADOR
    // ========================================

    const codigo =
        idioma.toUpperCase();

    botonIdioma.textContent =
        `🌐 ${codigo}`;


    // ========================================
    // GUARDAR
    // ========================================

    localStorage.setItem(
        "idiomaPagina",
        idioma
    );

}


// ============================================
// 🌎 IDIOMA GUARDADO
// ============================================

const idiomaGuardado =
    localStorage.getItem("idiomaPagina");


if (
    idiomaGuardado &&
    traducciones[idiomaGuardado]
) {

    cambiarIdioma(idiomaGuardado);

}
